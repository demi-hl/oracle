/** Unique venue brands, collapsing version variants. */
export function uniqueVenueBrands() {
  const norm = (s) => s.toLowerCase().replace(/\s+v[0-9]+$/, "").replace(/[^a-z0-9]/g, "");
  return new Set(JUPITER_VENUE_LABELS.map(norm));
}
